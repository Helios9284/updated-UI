def _row_is_same_origin_destination(row: dict) -> bool:
    if bool((row or {}).get("_same_origin_destination")):
        return True
    call = str((row or {}).get("call") or "").lower()
    call_token = call.split(".")[-1].split(" ")[0]
    if call_token not in _SPLIT_STAKE_CALL_TOKENS:
        return False
    raw = str((row or {}).get("netuid") or "").strip()
    if "->" not in raw:
        return False
    origin, destination = raw.split("->", 1)
    origin = origin.strip()
    destination = destination.strip()
    if not origin or not destination or origin == "-" or destination == "-":
        return False
    return origin == destination


def _read_env_values(path: Path):
    values = {}
    if not path.exists():
        return values
    try:
        text = path.read_text(encoding="utf-8")
    except Exception:
        return values
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        key, val = s.split("=", 1)
        values[key.strip()] = val.strip()
    return values


def _set_env_key(path: Path, key: str, value: str):
    line_out = f"{key}={value}"
    if not path.exists():
        path.write_text(line_out + "\n", encoding="utf-8")
        return
    lines = path.read_text(encoding="utf-8").splitlines()
    replaced = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in line:
            continue
        k = line.split("=", 1)[0].strip()
        if k == key:
            lines[i] = line_out
            replaced = True
            break
    if not replaced:
        lines.append(line_out)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


