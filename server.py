def _normalize_follow_stake_target(raw):
    if not isinstance(raw, dict):
        return None
    address = str(raw.get("address") or "").strip()
    if not address:
        return None
    source = str(raw.get("source") or "both").strip().lower()
    if source not in ("mempool", "block", "both"):
        source = "both"
    call_types_raw = raw.get("call_types") or []
    if isinstance(call_types_raw, str):
        call_types_raw = [part.strip() for part in call_types_raw.split(",")]
    call_types = set()
    for item in call_types_raw:
        side = str(item).strip().lower()
        if side in ("add", "remove"):
            call_types.add(side)
    if not call_types:
        call_types = {"add", "remove"}
    try:
        amount_tao = float(raw.get("amount_tao"))
    except (TypeError, ValueError):
        return None
    if amount_tao <= 0:
        return None
    try:
        slippage_pct = float(raw.get("slippage_pct", 0.5))
    except (TypeError, ValueError):
        slippage_pct = 0.5
    if slippage_pct < 0:
        slippage_pct = 0.0
    return {
        "address": address,
        "source": source,
        "call_types": sorted(call_types),
        "amount_tao": amount_tao,
        "slippage_pct": slippage_pct,
    }


def _parse_follow_stake_targets_env(raw: str):
    if not str(raw or "").strip():
        return []
    try:
        data = json.loads(raw)
    except Exception:
        return []
    if not isinstance(data, list):
        return []
    out = []
    for item in data:
        norm = _normalize_follow_stake_target(item)
        if norm:
            out.append(norm)
    return out


def _serialize_follow_stake_targets_for_env(targets):
    cleaned = []
    for item in targets or []:
        norm = _normalize_follow_stake_target(item)
        if norm:
            cleaned.append(norm)
    return json.dumps(cleaned, separators=(",", ":"))


def _extract_call_side(row: dict):
    row_type = str((row or {}).get("_row_type") or "").strip().lower()
    if row_type == "add":
        return "add"
    if row_type == "remove":
        return "remove"
    call = str((row or {}).get("call") or "").lower()
    if "add_stake" in call or "stakeadded" in call:
        return "add"
    if any(token in call for token in ("remove_stake", "unstake", "stakeremoved")):
        return "remove"
    return None


