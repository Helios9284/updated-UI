    def _portfolio_worker_loop(self):
        # warm once immediately
        warm = self._fetch_wallet_portfolio_once()
        self._apply_portfolio_cache(warm, warm.get("updated_at_block"))
        with self._block_cond:
            last_seen_seq = self._block_seq
        while not self._portfolio_stop.is_set():
            try:
                # Backward compatibility: if refresh sec is explicitly set (>0), use timer mode.
                if self._portfolio_refresh_sec > 0:
                    snap = self._fetch_wallet_portfolio_once()
                    self._apply_portfolio_cache(snap, snap.get("updated_at_block"))
                    self._portfolio_stop.wait(self._portfolio_refresh_sec)
                    continue

                # Default mode: refresh once per newly subscribed block header.
                seq, block_number = self._wait_for_new_block(
                    last_seen_seq,
                    self._portfolio_stop,
                    self._portfolio_block_poll_sec,
                )
                if seq == last_seen_seq:
                    continue
                last_seen_seq = seq
                if block_number is None:
                    continue
                # Coalesce: if multiple blocks arrived while we were fetching, refresh once
                # for the latest head instead of replaying every intermediate block.
                while True:
                    with self._block_cond:
                        latest_seq = self._block_seq
                        latest_block = self._latest_block_number
                    if latest_seq == last_seen_seq:
                        break
                    last_seen_seq = latest_seq
                    block_number = latest_block
                with self._portfolio_lock:
                    already = self._last_portfolio_refresh_block
                if block_number == already:
                    continue
                snap = self._fetch_wallet_portfolio_once()
                self._apply_portfolio_cache(snap, snap.get("updated_at_block") or block_number)
            except Exception:
                # Always rebuild the connection on any fetch error. A half-open
                # socket may raise a non-transient-looking error (or, with the
                # socket timeout, a timeout); reusing it would keep failing, so a
                # fresh connection is the only reliable recovery.
                self._portfolio_reconnect()
                with self._portfolio_lock:
                    self._last_portfolio_refresh_block = None

    def _block_subscriber_loop(self):
        while not self._block_stop.is_set():
            try:
                def _on_block(obj, _update_nr, _subscription_id):
                    if self._block_stop.is_set():
                        return {"stop": True}
                    header = obj.get("header") if isinstance(obj, dict) else None
                    if not isinstance(header, dict):
                        return None
                    block_number = parse_block_number(header.get("number"))
                    self._publish_new_block(block_number)
                    return None

                self._block_sub.subscribe_block_headers(_on_block)
            except Exception:
                if self._block_stop.is_set():
                    break
                with contextlib.suppress(Exception):
                    self._block_reconnect()
                time.sleep(1.0)

    def _block_head_poller_loop(self):
        # Polling fallback: if subscribe_block_headers misses or stalls, HEAD
        # polling still advances _block_seq so portfolio/nonce workers refresh.
        while not self._block_stop.is_set():
            try:
                block_number = self._fetch_head_block_number(self._block_poll_sub)
                self._publish_new_block(block_number)
            except Exception as exc:
                if _is_transient_rpc_error(exc):
                    with contextlib.suppress(Exception):
                        self._block_poll_reconnect()
            if self._block_stop.wait(self._block_head_poll_sec):
                break

    def get_block_status(self):
        with self._block_cond:
            payload = {
                "latest_block_number": self._latest_block_number,
                "block_seq": self._block_seq,
                "last_portfolio_refresh_block": self._last_portfolio_refresh_block,
                "head_poll_sec": self._block_head_poll_sec,
            }
        payload["mev_sign_window"] = self._mev_block_tracker_snapshot()
        return payload

    @staticmethod
    def _short_ss58(addr, head=6, tail=6):
        text = str(addr or "").strip()
        if len(text) <= head + tail + 2:
            return text or "-"
        return f"{text[:head]}..{text[-tail:]}"

    def _record_mev_error(self, message, *, code="mev_error"):
        text = str(message or "").strip()
        if not text:
            return
        with self._mev_meta_lock:
            self._mev_recent_errors.append(
                {
                    "ts": utc_now_iso(),
                    "code": str(code),
                    "message": text[:500],
                }
            )

