    def _run_identity_stake_submit(
        source, trigger, matched, netuid, block_number, detect_started, amount_tao, slippage_pct
    ):
        use_proxy = _resolve_identity_use_proxy()
        base_entry = {
            "ts": utc_now_iso(),
            "source": source,
            "trigger": trigger,
            "matched": matched,
            "netuid": int(netuid),
            "block_number": int(block_number) if block_number is not None else None,
            "amount_tao": float(amount_tao),
            "slippage_pct": float(slippage_pct),
            "use_proxy": bool(use_proxy),
            "mev_protection": True,
        }
        try:
            data = STAKE_SERVICE.submit_add(
                int(netuid),
                float(amount_tao),
                float(slippage_pct),
                bool(use_proxy),
                mev_protection=True,
            )
            tx_hash = (data or {}).get("tx_hash")
            _append_identity_stake_log(
                {
                    **base_entry,
                    "tx_hash": tx_hash,
                    "result": "submitted" if tx_hash else "ok",
                    "error": "",
                    "detect_ms": round((time.perf_counter() - detect_started) * 1000.0, 2),
                }
            )
        except Exception as exc:
            _append_identity_stake_log(
                {
                    **base_entry,
                    "result": "failed",
                    "error": str(exc),
                    "detect_ms": round((time.perf_counter() - detect_started) * 1000.0, 2),
                }
            )
        finally:
            with identity_stake_lock:
                identity_stake_inflight.discard(netuid)

    def handle_identity_stake_event(source: str, row: dict, block_number=None):
        detect_started = time.perf_counter()
        # User-confirmed: mempool sighting only (snipe before inclusion).
        if source != "mempool":
            return
        refresh_identity_stake_from_env(force=False)
        with identity_stake_lock:
            enabled = bool(identity_stake_enabled)
            amount_tao = float(identity_stake_amount_tao)
            slippage_pct = float(identity_stake_slippage_pct)
        if not enabled or amount_tao <= 0:
            return

        func = str((row or {}).get("call") or "").split(".")[-1].strip().lower()
        trigger = ""
        matched = ""
        netuids = []

        if func == "set_subnet_identity":
            trigger = "set_subnet_identity"
            matched = str((row or {}).get("signer") or "").strip()
            netuids = sorted(_extract_netuids_from_row(row))
        elif func in ("announce_coldkey_swap", "swap_coldkey_announced"):
            trigger = "coldkey_swap"
            _refresh_identity_owner_map(force=False)
            signer = str((row or {}).get("signer") or "").strip()
            if not signer or signer == "-":
                return
            with identity_stake_lock:
                owned = list(identity_owner_map.get(signer) or [])
            if not owned:
                return
            matched = signer
            netuids = owned
        else:
            return

        if not netuids:
            return

        block_key = int(block_number) if block_number is not None else None
        for netuid in netuids:
            with identity_stake_lock:
                submitted = identity_stake_submitted_by_block.setdefault(block_key, set())
                if netuid in submitted:
                    continue
                if netuid in identity_stake_inflight:
                    continue
                submitted.add(netuid)
                identity_stake_inflight.add(netuid)
                if len(identity_stake_submitted_by_block) > 64:
                    int_keys = sorted(
                        k for k in identity_stake_submitted_by_block if k is not None
                    )
                    for bn in int_keys[:-32]:
                        identity_stake_submitted_by_block.pop(bn, None)
            threading.Thread(
                target=_run_identity_stake_submit,
                args=(
                    source,
                    trigger,
                    matched,
                    int(netuid),
                    block_number,
                    detect_started,
                    amount_tao,
                    slippage_pct,
                ),
                name=f"identity-stake-{netuid}",
                daemon=True,
            ).start()

    def _extract_addresses_for_match(row: dict):
        values = set()
        for key in ("real_address", "signer", "hotkey", "to"):
            val = str((row or {}).get(key) or "").strip()
            if val and val != "-":
                values.add(val)
        return values

    def _extract_netuids_from_row(row: dict):
        raw = str((row or {}).get("netuid") or "").strip()
        if not raw or raw == "-":
            return set()
        out = set()
        for match in re.findall(r"\d+", raw):
            with contextlib.suppress(Exception):
                out.add(int(match))
        return out

