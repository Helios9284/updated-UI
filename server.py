    def _nonce_watcher_loop(self):
        with contextlib.suppress(Exception):
            self._refresh_nonce_cache_once(force=True, use_nonce_sub=True)
        with self._block_cond:
            last_seen_seq = self._block_seq
        while not self._nonce_stop.is_set():
            try:
                seq, block_number = self._wait_for_new_block(
                    last_seen_seq,
                    self._nonce_stop,
                    self._nonce_refresh_poll_sec,
                )
                if seq == last_seen_seq:
                    continue
                last_seen_seq = seq
                self._refresh_nonce_cache_once(
                    force=False, block_number=block_number, use_nonce_sub=True
                )
                with self._mev_meta_lock:
                    inflight_addrs = list(self._mev_inflight.items())
                for addr, inflight in inflight_addrs:
                    if not inflight:
                        continue
                    with self._lock:
                        chain = self._nonce_chain_cache.get(addr)
                    outer = int(inflight.get("outer_nonce", -1))
                    if chain is None:
                        continue
                    # Only refresh hint/cache — submit path owns inflight clear.
                    # Watcher clearing mid-op caused 연타 cancel/assert races.
                    if self._mev_inflight_resolved_nonce(outer, int(chain)):
                        with self._lock:
                            hinted = self._nonce_hint.get(addr)
                            if hinted is None or int(hinted) < int(chain):
                                self._nonce_hint[addr] = int(chain)
                            self._nonce_chain_cache[addr] = int(chain)
                self._keepalive_warm_conns()
            except Exception as exc:
                if _is_transient_rpc_error(exc):
                    with contextlib.suppress(Exception):
                        self._nonce_reconnect()
                self._last_nonce_refresh_block = None

    def _keepalive_warm_conns(self):
        # Keep the submit (self._sub) and read (self._read_sub) connections warm
        # so the node does not close them as idle during quiet periods, which
        # would otherwise surface as a broken pipe on the next submit. Each ping
        # runs under that connection's own lock so it never interleaves with a
        # concurrent submit/compose on the same socket. Throttled so it adds
        # negligible overhead.
        now = time.monotonic()
        if now - self._last_keepalive_ts < self._keepalive_interval_sec:
            return
        self._last_keepalive_ts = now
        with contextlib.suppress(Exception):
            with self._lock:
                self._sub.rpc_request("chain_getHeader", [])
        with contextlib.suppress(Exception):
            with self._read_lock:
                self._read_sub.rpc_request("chain_getHeader", [])
    def wallet_portfolio_snapshot(self):
        with self._portfolio_lock:
            snap = dict(self._portfolio_cache)
            snap["updated_at_block"] = self._last_portfolio_refresh_block
            return snap

    @staticmethod
    def _stake_hotkeys_for_netuid(snapshot, netuid):
        nu = int(netuid)
        hotkeys = []
        seen = set()
        for row in list((snapshot or {}).get("stakes") or []):
            if to_int((row or {}).get("netuid")) != nu:
                continue
            hk = str((row or {}).get("hotkey") or "").strip()
            if not hk or hk in seen:
                continue
            seen.add(hk)
            hotkeys.append(hk)
        return hotkeys

    def _portfolio_cache_is_current(self):
        # The cache is "current" when the per-block portfolio worker has already
        # refreshed it for the latest known block. In that state a netuid miss
        # means we genuinely don't own it, so we can skip without a blocking
        # refetch on the hot path.
        with self._block_cond:
            latest = self._latest_block_number
        last = self._last_portfolio_refresh_block
        if latest is None or last is None:
            return False
        return int(last) >= int(latest)

    def _fetch_owned_hotkeys_for_netuid(self, netuid):
        # Lightweight hot-path lookup for the auto-unstake bot: returns the
        # hotkeys holding stake on `netuid` using a SINGLE stake state_call (no
        # prices / rewards / account reads like the full portfolio fetch). Runs
        # on a dedicated short-timeout connection so it never contends with the
        # per-block portfolio worker and never blocks longer than a few seconds.
        nu = int(netuid)
        with self._unstake_sub_lock:
            sub = self._unstake_sub
            try:
                head = sub.rpc_request("chain_getHeader", [])["result"]
                block_number = parse_block_number(head.get("number"))
                block_hash = sub.rpc_request("chain_getBlockHash", [block_number])["result"]
                addr_hex = ss58_decode(self.signer_ss58)
                result = sub.rpc_request(
                    "state_call",
                    [
                        "StakeInfoRuntimeApi_get_stake_info_for_coldkey",
                        "0x" + addr_hex,
                        block_hash,
                    ],
                )
                raw = result.get("result", "0x00")
                entries = decode_stake_info_raw(bytes.fromhex(raw[2:]))
                hotkeys = []
                seen = set()
                for e in entries:
                    if int(e.netuid) != nu or e.stake_rao == 0:
                        continue
                    hk = str(e.hotkey or "").strip()
                    if hk and hk not in seen:
                        seen.add(hk)
                        hotkeys.append(hk)
                return hotkeys
            except Exception:
                # Half-open socket or decode error: rebuild for next time and let
                # the caller fall back to the cached snapshot decision.
                with contextlib.suppress(Exception):
                    self._unstake_sub.close()
                with contextlib.suppress(Exception):
                    self._unstake_sub = self._new_substrate(
                        self.read_endpoint, timeout=self._unstake_rpc_timeout_sec
                    )
                return None

    def remove_full_if_owned_netuid(self, netuid, use_proxy=False, mev_protection=False):
        nu = int(netuid)
        snapshot = self.wallet_portfolio_snapshot()
        hotkeys = self._stake_hotkeys_for_netuid(snapshot, nu)
        if not hotkeys and not self._portfolio_cache_is_current():
            # Cache lags the latest block (brief window right after a new block,
            # before the per-block worker refreshes). Do a lightweight, isolated
            # hotkey-only lookup instead of a full portfolio refetch on the
            # shared worker connection (which corrupts that socket and can stall
            # for the full RPC timeout). When the cache is already current a miss
            # means we genuinely don't own it, so we skip immediately.
            fresh = self._fetch_owned_hotkeys_for_netuid(nu)
            if fresh:
                hotkeys = fresh
        if not hotkeys:
            return {
                "ok": True,
                "success": True,
                "submitted": False,
                "skipped": True,
                "reason": "netuid_not_in_portfolio",
                "netuid": nu,
            }
        submitted = []
        errors = []
        last_data = None
        for hk in hotkeys:
            try:
                last_data = self.submit_remove_full(
                    nu,
                    bool(use_proxy),
                    mev_protection=bool(mev_protection),
                    hotkey=hk,
                )
                submitted.append({"hotkey": hk, "tx_hash": last_data.get("tx_hash")})
            except Exception as exc:
                errors.append({"hotkey": hk, "error": str(exc)})
        if not submitted:
            return {
                "ok": False,
                "success": False,
                "submitted": False,
                "skipped": False,
                "reason": "remove_failed",
                "netuid": nu,
                "errors": errors,
            }
        return {
            "ok": True,
            "success": True,
            "submitted": True,
            "skipped": False,
            "reason": "",
            "netuid": nu,
            "n_removed": len(submitted),
            "removed": submitted,
            "errors": errors,
            **(last_data or {}),
        }

    @staticmethod
    def _effective_slippage_pct(slippage_pct, mev_protection=False):
        """MEV-encrypted orders force 100% slip (price impact is not relevant)."""
        if mev_protection:
            return 100.0
        return float(slippage_pct)

    def _limit_price_rao(self, netuid, slippage_pct, side, *, alpha_price_tao_hint=None):
        slippage = float(slippage_pct)
        if slippage < -0.5:
            raise RuntimeError("slippage_pct must be >= -0.5")
        alpha_price_tao = None
        price_block = None
        if alpha_price_tao_hint is not None:
            try:
                hinted = float(alpha_price_tao_hint)
                if hinted > 0:
                    alpha_price_tao = hinted
                    _, price_block = self._alpha_price_cache.snapshot()
            except Exception:
                alpha_price_tao = None
        if alpha_price_tao is None:
            alpha_price_tao, price_block = self._cached_alpha_price_tao(
                int(netuid), min_block=None
            )

        # MEV path forces 100% slip — skip blocking direct price RPC.
        # Impact: compose finishes in cache time so soft-window sees click age.
        # Risk: none for remove (limit 0). For add, cache miss uses an open
        # limit (same economic intent as 100% tolerance). Non-MEV unchanged.
        if slippage >= 100.0:
            if str(side) == "remove":
                return 0, float(alpha_price_tao or 0.0), price_block
            if alpha_price_tao is not None and float(alpha_price_tao) > 0:
                price = float(alpha_price_tao) * (1.0 + slippage / 100.0)
                return int(price * 1_000_000_000), float(alpha_price_tao), price_block
            return 10**18, 0.0, price_block

        if alpha_price_tao is None:
            alpha_price_tao, price_block = self._direct_alpha_price_tao(int(netuid))
        if side == "add":
            price = alpha_price_tao * (1.0 + slippage / 100.0)
        else:
            price = alpha_price_tao * (1.0 - slippage / 100.0)
            if price < 0:
                price = 0.0
        limit_price = int(price * 1_000_000_000)
        return limit_price, alpha_price_tao, price_block

