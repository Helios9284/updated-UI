def verify_token(authorization):
    if not authorization:
        raise HTTPException(status_code=401, detail="missing authorization header")
    prefix = "Bearer "
    if not str(authorization).startswith(prefix):
        raise HTTPException(status_code=401, detail="authorization must be Bearer token")
    token = authorization[len(prefix) :].strip()
    if token != STAKE_CONFIG.token:
        raise HTTPException(status_code=401, detail="invalid token")


def verify_transfer_stake_password(payload: dict) -> str | None:
    """Return an error message when the transfer confirmation password is wrong."""
    expected = (os.getenv("TRANSFER_STAKE_PASSWORD") or "").strip()
    if not expected:
        return "TRANSFER_STAKE_PASSWORD is not configured on the server"
    provided = str((payload or {}).get("password") or "").strip()
    if not provided:
        return "password is required for transfer_stake"
    if not secrets.compare_digest(provided, expected):
        return "invalid transfer password"
    return None


async def _run_stake_submit(fn, mev_protection=False):
    timeout = STAKE_MEV_TIMEOUT_SEC if mev_protection else STAKE_CONFIG.timeout_sec
    try:
        return await asyncio.wait_for(asyncio.to_thread(fn), timeout=timeout)
    except asyncio.TimeoutError:
        if mev_protection:
            # Stop the orphaned to_thread worker so it clears inflight/nonce.
            STAKE_SERVICE.cancel_mev_ops()
        raise RuntimeError(
            f"MEV/stake submit timed out after {timeout:.0f}s "
            "(worker cancelled; retry or POST /api/nonce/refresh)"
        ) from None


