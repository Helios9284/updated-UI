    @app.websocket("/ws")
    async def ws_endpoint(ws: WebSocket):
        ok = await state.add_client(ws)
        if not ok:
            return
        try:
            while True:
                # Keep connection open; server pushes snapshots.
                await ws.receive_text()
        except WebSocketDisconnect:
            pass
        finally:
            await state.remove_client(ws)

