def _read_compact(data: bytes, pos: int):
    first = data[pos]
    mode = first & 0b11
    if mode == 0:
        return first >> 2, pos + 1
    if mode == 1:
        return int.from_bytes(data[pos : pos + 2], "little") >> 2, pos + 2
    if mode == 2:
        return int.from_bytes(data[pos : pos + 4], "little") >> 2, pos + 4
    n = (first >> 2) + 4
    return int.from_bytes(data[pos + 1 : pos + 1 + n], "little"), pos + 1 + n


def _to_int(value):
    try:
        if hasattr(value, "value"):
            value = value.value
        if value is None:
            return None
        return int(value)
    except Exception:
        return None


def decode_stake_info_raw(data: bytes):
    results = []
    vec_len, pos = _read_compact(data, 0)
    for _ in range(vec_len):
        hk = ss58_encode(data[pos : pos + 32].hex(), ss58_format=42)
        pos += 32
        pos += 32  # coldkey
        netuid, pos = _read_compact(data, pos)
        stake, pos = _read_compact(data, pos)
        locked, pos = _read_compact(data, pos)
        _emission, pos = _read_compact(data, pos)
        tao_emission, pos = _read_compact(data, pos)
        _drain, pos = _read_compact(data, pos)
        is_reg = bool(data[pos])
        pos += 1
        results.append(
            StakeEntry(
                hotkey=hk,
                netuid=netuid,
                stake_rao=stake,
                locked_rao=locked,
                tao_emission_rao=tao_emission,
                is_registered=is_reg,
            )
        )
    return results


def _free_balance_rao(sub: SubstrateInterface, address: str):
    account = sub.query("System", "Account", [address])
    account_v = getattr(account, "value", {}) or {}
    return _to_int(account_v.get("data", {}).get("free")) or 0


def _fetch_portfolio_with_sub(
    sub: SubstrateInterface,
    address: str,
    alpha_prices_tao_by_netuid: dict[int, float],
):
    addr_hex = ss58_decode(address)
    t0 = time.time()
    result = sub.rpc_request(
        "state_call",
        ["StakeInfoRuntimeApi_get_stake_info_for_coldkey", "0x" + addr_hex],
    )
    raw = result.get("result", "0x00")
    data = bytes.fromhex(raw[2:])
    entries = decode_stake_info_raw(data)
    free_rao = _free_balance_rao(sub, address)

    rows = []
    total_tao = 0.0
    for e in entries:
        if e.stake_rao == 0:
            continue
        alpha = e.stake_rao / 1_000_000_000
        if e.netuid == 0:
            tao_val = alpha
        else:
            price = alpha_prices_tao_by_netuid.get(e.netuid)
            tao_val = alpha * price if price and price > 0 else 0.0
        total_tao += tao_val
        hk = e.hotkey
        rows.append(
            {
                "hotkey": hk,
                "hotkey_short": f"{hk[:6]}...{hk[-6:]}" if len(hk) > 14 else hk,
                "netuid": e.netuid,
                "tao": round(tao_val, 4),
                "alpha": round(alpha, 4),
                "locked": round(e.locked_rao / 1_000_000_000, 4),
                "emission": round(e.tao_emission_rao / 1_000_000_000, 6),
                "registered": e.is_registered,
            }
        )
    rows.sort(key=lambda r: r["tao"], reverse=True)
    fetch_ms = (time.time() - t0) * 1000.0
    return {
        "address": address,
        "portfolio": rows,
        "portfolio_total_tao": round(total_tao, 4),
        "free_balance": round(free_rao / 1_000_000_000, 4),
        "fetch_ms": round(fetch_ms, 0),
    }


class PortfolioQueryService:
    def __init__(self, endpoint: str):
        self.endpoint = endpoint
        self._lock = threading.Lock()
        self._sub = None

    def _ensure(self):
        if self._sub is None:
            self._sub = _new_substrate(self.endpoint)
        return self._sub

    def close(self):
        with self._lock:
            if self._sub is not None:
                with contextlib.suppress(Exception):
                    self._sub.close()
                self._sub = None

    def fetch(self, address: str, alpha_prices_tao_by_netuid: dict[int, float]):
        started = time.time()
        with self._lock:
            sub = self._ensure()
            try:
                result = _fetch_portfolio_with_sub(sub, address, alpha_prices_tao_by_netuid)
            except Exception:
                # Reconnect once and retry.
                with contextlib.suppress(Exception):
                    sub.close()
                self._sub = _new_substrate(self.endpoint)
                result = _fetch_portfolio_with_sub(
                    self._sub, address, alpha_prices_tao_by_netuid
                )
        result["total_fetch_ms"] = round((time.time() - started) * 1000.0, 0)
        return result


