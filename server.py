    def _run_auto_unstake_submit(source, matched, netuid, block_number, detect_started):
        # Runs in a worker thread: performs the blocking HTTP submit + logging so
        # the detection loop (mempool/block collectors) is never stalled on RPC.
        try:
            res = _submit_auto_unstake_to_stake_server(netuid)
            ok = bool(isinstance(res, dict) and res.get("ok"))
            submitted_flag = bool(isinstance(res, dict) and res.get("submitted"))
            skipped = bool(isinstance(res, dict) and res.get("skipped"))
            reason = str((res or {}).get("reason") or "") if isinstance(res, dict) else ""
            _append_auto_unstake_log(
                {
                    "ts": utc_now_iso(),
                    "source": source,
                    "address": matched,
                    "netuid": int(netuid),
                    "block_number": int(block_number) if block_number is not None else None,
                    "tx_hash": (res or {}).get("tx_hash") if isinstance(res, dict) else None,
                    "n_removed": (res or {}).get("n_removed") if isinstance(res, dict) else None,
                    "removed": (res or {}).get("removed") if isinstance(res, dict) else None,
                    "result": "submitted" if submitted_flag else ("skipped" if skipped else ("ok" if ok else "failed")),
                    "reason": reason,
                    "error": "" if ok else str((res or {}).get("error") if isinstance(res, dict) else res),
                    "detect_ms": round((time.perf_counter() - detect_started) * 1000.0, 2),
                }
            )
        except Exception as exc:
            _append_auto_unstake_log(
                {
                    "ts": utc_now_iso(),
                    "source": source,
                    "address": matched,
                    "netuid": int(netuid),
                    "result": "failed",
                    "error": str(exc),
                }
            )
        finally:
            with auto_unstake_lock:
                auto_unstake_inflight.discard(netuid)

    def handle_auto_unstake_event(source: str, row: dict, block_number=None):
        detect_started = time.perf_counter()
        if source not in ("mempool", "block"):
            return
        if source == "mempool" and row.get("proxy_fake"):
            return
        if source == "block" and not _block_row_extrinsic_succeeded(row):
            return
        if _row_is_same_origin_destination(row):
            return
        refresh_auto_unstake_from_env(force=False)
        with auto_unstake_lock:
            enabled = bool(auto_unstake_enabled)
            targets = set(auto_unstake_mempool_targets if source == "mempool" else auto_unstake_block_targets)
        if not enabled or not targets:
            return
        addresses = _extract_addresses_for_match(row)
        matched = next((a for a in addresses if a in targets), None)
        if not matched:
            return

        candidate_netuids = sorted(_extract_netuids_from_row(row))
        if not candidate_netuids:
            return
        # Dedup is scoped to a single block only: the same netuid is submitted at
        # most once per block. When a new block arrives, the same netuid may be
        # submitted again (e.g. the target acts again in a later block).
        block_key = int(block_number) if block_number is not None else None
        for netuid in candidate_netuids:
            with auto_unstake_lock:
                submitted = auto_unstake_submitted_by_block.setdefault(block_key, set())
                if netuid in submitted:
                    # Already handled this netuid in this block (e.g. repeated
                    # mempool polls or a mempool+block double-detect). Skip quietly.
                    continue
                if netuid in auto_unstake_inflight:
                    continue
                submitted.add(netuid)
                auto_unstake_inflight.add(netuid)
                if len(auto_unstake_submitted_by_block) > 64:
                    int_keys = sorted(k for k in auto_unstake_submitted_by_block if k is not None)
                    for bn in int_keys[:-32]:
                        auto_unstake_submitted_by_block.pop(bn, None)
            # Offload the blocking submit to a worker thread so the detection loop
            # keeps polling without waiting on the stake server / chain RPC.
            threading.Thread(
                target=_run_auto_unstake_submit,
                args=(source, matched, int(netuid), block_number, detect_started),
                name=f"auto-unstake-{netuid}",
                daemon=True,
            ).start()

