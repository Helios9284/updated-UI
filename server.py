    @staticmethod
    def _read_env(key):
        return os.getenv(key)

    def _wallet_path(self, wallet_name, *parts):
        return os.path.join(self.wallets_dir, wallet_name, *parts)

    def _load_wallet_coldkey(self, *, label, wallet_name, password):
        path = Path(self._wallet_path(wallet_name, "coldkey"))
        if not path.exists():
            raise RuntimeError(f"{label}: coldkey not found at {path}")
        encrypted = False
        with contextlib.suppress(Exception):
            encrypted = keyfile_data_is_encrypted(path.read_bytes())
        if encrypted and not password:
            raise RuntimeError(f"{label}: password required for encrypted coldkey")
        wallet = Wallet(name=wallet_name, path=self.wallets_dir)
        try:
            return wallet.get_coldkey(password=password or None)
        except Exception as exc:
            if encrypted:
                raise RuntimeError(
                    f"{label}: failed to unlock coldkey for wallet '{wallet_name}': {exc}"
                ) from exc
            raise RuntimeError(f"{label}: failed to load coldkey for wallet '{wallet_name}': {exc}") from exc

    def _looks_like_ss58_address(self, value):
        text = str(value or "").strip()
        if not text:
            return False
        try:
            ss58_decode(text)
            return True
        except Exception:
            return False

    def _resolve_hotkey_ss58(self, *, wallet_name, hotkey_ref):
        raw = str(hotkey_ref or "").strip()
        if not raw:
            return ""
        if self._looks_like_ss58_address(raw):
            return raw
        pub_path = Path(self.wallets_dir) / wallet_name / "hotkeys" / f"{raw}pub.txt"
        if pub_path.exists():
            try:
                data = json.loads(pub_path.read_text(encoding="utf-8"))
                ss58 = str(data.get("ss58Address") or "").strip()
                if ss58:
                    return ss58
            except Exception:
                pass
        # fallback: allow direct raw value if user already passed ss58-like custom format
        return raw

    def _new_substrate(self, endpoint=None, timeout=None):
        url = endpoint or self.config.endpoint
        # A socket timeout makes request/reply RPC calls raise instead of
        # blocking forever on a half-open connection (which previously froze the
        # portfolio worker). NOT applied to the block-header subscription, which
        # legitimately waits ~12s between pushed headers.
        ws_options = {"timeout": float(timeout)} if timeout and timeout > 0 else None
        sub = SubstrateInterface(
            url=url,
            type_registry_preset="substrate-node-template",
            ws_options=ws_options,
        )
        sub.init_runtime()
        return sub

    def close(self):
        self._block_stop.set()
        self._nonce_stop.set()
        self._portfolio_stop.set()
        with self._block_cond:
            self._block_cond.notify_all()
        if self._block_thread.is_alive():
            with contextlib.suppress(Exception):
                self._block_thread.join(timeout=1.0)
        if self._block_head_poll_thread.is_alive():
            with contextlib.suppress(Exception):
                self._block_head_poll_thread.join(timeout=1.0)
        if self._nonce_thread.is_alive():
            with contextlib.suppress(Exception):
                self._nonce_thread.join(timeout=1.0)
        if self._portfolio_thread.is_alive():
            with contextlib.suppress(Exception):
                self._portfolio_thread.join(timeout=1.0)
        with contextlib.suppress(Exception):
            self._block_sub.close()
        with contextlib.suppress(Exception):
            self._block_poll_sub.close()
        with contextlib.suppress(Exception):
            self._portfolio_sub.close()
        with contextlib.suppress(Exception):
            self._nonce_sub.close()
        with contextlib.suppress(Exception):
            self._unstake_sub.close()
        with contextlib.suppress(Exception):
            self._mev_watch_sub.close()
        with contextlib.suppress(Exception):
            self._read_sub.close()
        with contextlib.suppress(Exception):
            self._sub.close()
        owned_cache = self._owned_alpha_price_cache
        if owned_cache is not None:
            with contextlib.suppress(Exception):
                owned_cache.stop()

    def attach_alpha_price_cache(self, cache: AlphaPriceCache):
        """Use the dashboard AlphaPriceCache when both apps run in one process."""
        if cache is self._alpha_price_cache:
            return
        owned = self._owned_alpha_price_cache
        if owned is not None and owned is not cache:
            with contextlib.suppress(Exception):
                owned.stop()
            self._owned_alpha_price_cache = None
        self._alpha_price_cache = cache

    def _reconnect(self):
        with contextlib.suppress(Exception):
            self._sub.close()
        self._sub = self._new_substrate(timeout=self._rpc_timeout_sec)
        # Stale Call objects after reconnect/runtime upgrade encode wrong SCALE
        # and surface as Subtensor UnknownError / ItemFailed.
        self._remove_full_call_cache = {}
        self._invalidate_mev_sign_caches()

    def _mev_watch_reconnect(self):
        """Rebuild the MEV watch socket (caller should hold _mev_watch_lock)."""
        with contextlib.suppress(Exception):
            self._mev_watch_sub.close()
        self._mev_watch_sub = self._new_substrate(
            self.read_endpoint, timeout=self._rpc_timeout_sec
        )

    def _nonce_reconnect(self):
        with contextlib.suppress(Exception):
            self._nonce_sub.close()
        self._nonce_sub = self._new_substrate(timeout=self._rpc_timeout_sec)

    def _read_reconnect(self):
        with contextlib.suppress(Exception):
            self._read_sub.close()
        self._read_sub = self._new_substrate(self.read_endpoint, timeout=self._rpc_timeout_sec)
        self._remove_full_call_cache = {}

    def _prewarm_rpc(self):
        started = time.time()
        try:
            # 1) Chain header ping
            self._with_rpc_retry(
                lambda: self._sub.rpc_request("chain_getHeader", []),
                attempts=3,
                label="prewarm_header",
            )
            # 2) Nonce cache warmup
            self._refresh_nonce_cache_once(force=True)
            # 3) Price cache warmup (shared AlphaPriceCache snapshot)
            _ = self._alpha_price_cache.snapshot()
            # 4) Compose warmup for frequently used calls
            dummy_add = {
                "hotkey": self._validator_hotkey_for_add(0),
                "netuid": 0,
                "amount_staked": 1,
                "limit_price": 1_000_000_000,
                "allow_partial": True,
            }
            self._compose_call("add_stake_limit", dummy_add, use_proxy=False)
            if self.proxy_ss58:
                self._compose_call("add_stake_limit", dummy_add, use_proxy=True)
            # Warm the remove_stake_full_limit metadata/compose path too, and seed
            # the call cache for netuid 0 so the first auto-unstake is not cold.
            warm_remove_hk = self._portfolio_hotkey_for_netuid(0) or self.default_hotkey
            with contextlib.suppress(Exception):
                self._compose_remove_full_call(0, warm_remove_hk, use_proxy=False)
                if self.proxy_ss58:
                    self._compose_remove_full_call(0, warm_remove_hk, use_proxy=True)
            self._prewarm_ok = True
            self._prewarm_error = ""
        except Exception as exc:
            self._prewarm_ok = False
            self._prewarm_error = str(exc)
        finally:
            self._prewarm_ms = round((time.time() - started) * 1000.0, 0)

    def _with_rpc_retry_conn(self, get_sub, reconnect, fn, attempts=3, label="rpc"):
        last_exc = None
        for _ in range(max(1, int(attempts))):
            try:
                return fn(get_sub())
            except Exception as exc:
                last_exc = exc
                if _is_transient_rpc_error(exc):
                    reconnect()
                    time.sleep(0.05)
                    continue
                raise
        if last_exc is not None:
            raise RuntimeError(f"{label} failed after retries: {last_exc}") from last_exc
        raise RuntimeError(f"{label} failed without exception")

    def _with_rpc_retry(self, fn, attempts=3, label="rpc"):
        # Backwards-compatible wrapper: fn closes over self._sub directly.
        return self._with_rpc_retry_conn(
            lambda: self._sub,
            self._reconnect,
            lambda _s: fn(),
            attempts=attempts,
            label=label,
        )

    def _with_watch_retry(self, fn, attempts=3, label="mev_watch"):
        """RPC on _mev_watch_sub. Takes _mev_watch_lock per attempt (RLock-safe)."""
        last_exc = None
        for _ in range(max(1, int(attempts))):
            try:
                with self._mev_watch_lock:
                    return fn(self._mev_watch_sub)
            except Exception as exc:
                last_exc = exc
                if _is_transient_rpc_error(exc):
                    with self._mev_watch_lock:
                        self._mev_watch_reconnect()
                    time.sleep(0.05)
                    continue
                raise
        if last_exc is not None:
            raise RuntimeError(f"{label} failed after retries: {last_exc}") from last_exc
        raise RuntimeError(f"{label} failed without exception")

    def _with_read_retry(self, fn, attempts=3, label="read"):
        # Runs read-only RPCs (alpha price, compose) on the dedicated _read_sub,
        # serialized by _read_lock instead of self._lock so it overlaps submits.
        with self._read_lock:
            return self._with_rpc_retry_conn(
                self._get_read_sub,
                self._read_reconnect,
                lambda s: fn(s),
                attempts=attempts,
                label=label,
            )

    def _get_read_sub(self):
        return self._read_sub

    def _active_signer_addresses(self):
        out = [self.signer_ss58]
        if self.proxy_ss58:
            out.append(self.proxy_ss58)
        return out

    def _refresh_nonce_cache_once(self, force=False, block_number=None, use_nonce_sub=False):
        # The background nonce watcher passes use_nonce_sub=True so its RPC runs
        # on the dedicated _nonce_sub connection, never on the submit hot path's
        # self._sub. Submit-side callers (prewarm/manual) use self._sub under the
        # lock.
        if use_nonce_sub:
            get_sub, reconnect = (lambda: self._nonce_sub), self._nonce_reconnect
        else:
            get_sub, reconnect = (lambda: self._sub), self._reconnect
        if force:
            header = self._with_rpc_retry_conn(
                get_sub,
                reconnect,
                lambda s: s.rpc_request("chain_getHeader", []),
                attempts=3,
                label="nonce_refresh_header",
            )
            block_hex = (header or {}).get("result", {}).get("number")
            block_number = parse_block_number(block_hex)
        elif block_number is None:
            with self._block_cond:
                block_number = self._latest_block_number
        if (
            not force
            and block_number is not None
            and block_number == self._last_nonce_refresh_block
        ):
            return False

        latest = {}
        for addr in self._active_signer_addresses():
            latest[addr] = self._with_rpc_retry_conn(
                get_sub,
                reconnect,
                lambda s, a=addr: s.get_account_nonce(a),
                attempts=3,
                label=f"nonce_refresh_{addr[:8]}",
            )

        with self._lock:
            for addr, chain_nonce in latest.items():
                chain_nonce = int(chain_nonce)
                self._nonce_chain_cache[addr] = chain_nonce
                hinted = self._nonce_hint.get(addr)
                # Only pull back hints more than one full MEV round ahead of chain.
                # (hint=N+2, chain=N+1 is normal settle lag — do not reset to N+1.)
                if hinted is not None and int(hinted) > chain_nonce + 2:
                    self._nonce_hint[addr] = chain_nonce
            if block_number is not None:
                self._last_nonce_refresh_block = block_number
        return True

    def _mev_nonce_settle_sec(self):
        # Ceiling only — pollers return as soon as chain nonce reaches the target.
        # Consecutive MEV is not held for the full window once N+2 is visible.
        raw = (self._read_env("STAKE_MEV_NONCE_SETTLE_SEC") or "").strip()
        if raw:
            try:
                return float(raw)
            except Exception:
                pass
        estimated = self._estimated_mev_block_duration_sec()
        return max(6.0, min(20.0, float(estimated) * 1.25 + 2.0))

    def _fetch_chain_nonce(self, signer_addr, *, sub=None):
        """Fresh on-chain next nonce — used by MEV path instead of the fast hint.

        Pass sub=... for the MEV watch path (caller holds _mev_watch_lock). Always
        rebinds to the current _mev_watch_sub so a mid-retry reconnect cannot leave
        us on a closed socket.
        """
        if sub is not None:
            return int(
                self._with_watch_retry(
                    lambda s: s.get_account_nonce(signer_addr),
                    attempts=3,
                    label="fetch_chain_nonce_watch",
                )
            )
        return int(
            self._with_rpc_retry(
                lambda: self._sub.get_account_nonce(signer_addr),
                attempts=3,
                label="fetch_chain_nonce",
            )
        )

    def _commit_nonce_after_success(self, signer_addr, next_nonce):
        next_nonce = int(next_nonce)
        self._nonce_hint[signer_addr] = next_nonce
        self._nonce_chain_cache[signer_addr] = next_nonce

    def _reconcile_nonce_after_mev_failure(self, signer_addr):
        """Reset local nonce state to chain after a failed/pending MEV round."""
        chain_nonce = self._fetch_chain_nonce(signer_addr)
        self._commit_nonce_after_success(signer_addr, chain_nonce)
        return chain_nonce

    def _set_mev_inflight(self, signer_addr, outer_nonce, wrapper_hash):
        with self._mev_meta_lock:
            self._mev_inflight[signer_addr] = {
                "outer_nonce": int(outer_nonce),
                "wrapper_hash": _norm_extrinsic_hash(wrapper_hash),
                "started_at": time.monotonic(),
            }
        # Hold hint at outer nonce until wrapper fate is known (never overshoot to N+2).
        with self._lock:
            self._nonce_hint[signer_addr] = int(outer_nonce)
            self._nonce_chain_cache[signer_addr] = int(outer_nonce)

    def _get_mev_signer_lock(self, signer_addr):
        with self._mev_meta_lock:
            lock = self._mev_signer_locks.get(signer_addr)
            if lock is None:
                lock = threading.Lock()
                self._mev_signer_locks[signer_addr] = lock
            return lock

    def _clear_mev_inflight(self, signer_addr):
        with self._mev_meta_lock:
            self._mev_inflight.pop(signer_addr, None)

    def _clear_mev_inflight_if_match(
        self, signer_addr, *, outer_nonce=None, wrapper_hash=None
    ):
        """Clear inflight only when it still belongs to this attempt (cancel race-safe)."""
        if outer_nonce is None and not wrapper_hash:
            return False
        want_hash = _norm_extrinsic_hash(wrapper_hash) if wrapper_hash else ""
        with self._mev_meta_lock:
            row = self._mev_inflight.get(signer_addr)
            if not row:
                return False
            if outer_nonce is not None and int(row.get("outer_nonce", -1)) != int(
                outer_nonce
            ):
                return False
            if want_hash and str(row.get("wrapper_hash") or "") != want_hash:
                return False
            self._mev_inflight.pop(signer_addr, None)
            return True

    @staticmethod
    def _hash_extrinsic_hex(ext_hex):
        """Blake2-256 of SCALE extrinsic bytes — matches on-chain extrinsic hash."""
        text = str(ext_hex or "").strip()
        if not text:
            return ""
        if text.startswith("0x"):
            text = text[2:]
        try:
            raw = bytes.fromhex(text)
        except ValueError:
            return ""
        return "0x" + blake2b(raw, digest_size=32).hexdigest()

    def _decoded_extrinsic_hash(self, decoded, ext_hex):
        h = (decoded or {}).get("hash")
        if isinstance(h, (bytes, bytearray)):
            return f"0x{bytes(h).hex()}"
        text = str(h or "").strip()
        if text.startswith("0x") and len(text) >= 66:
            return _norm_extrinsic_hash(text)
        # str(bytes) → "b'\\x..'" is unusable; prefer blake2 of raw hex.
        hashed = self._hash_extrinsic_hex(ext_hex)
        if hashed:
            return hashed
        try:
            from scalecodec import ScaleBytes

            extrinsic = self._sub.runtime_config.create_scale_object(
                "Extrinsic", metadata=self._sub.metadata
            )
            extrinsic.decode(
                ScaleBytes(ext_hex),
                check_remaining=self._sub.config.get("strict_scale_decode"),
            )
            raw_h = getattr(extrinsic, "extrinsic_hash", None)
            if isinstance(raw_h, (bytes, bytearray)):
                return f"0x{bytes(raw_h).hex()}"
            if hasattr(raw_h, "hex"):
                return f"0x{raw_h.hex()}"
            return _norm_extrinsic_hash(str(raw_h or ""))
        except Exception:
            return _norm_extrinsic_hash(text) if text and not text.startswith("b'") else ""

    def _pending_has_wrapper(self, signer_addr, wrapper_hash=None, outer_nonce=None, sub=None):
        """
        True if wrapper is in pending pool.
        None if the pending query failed (unknown — do not treat as dropped).
        False if the pool was scanned and the wrapper was absent.
        """
        sub = sub or self._sub
        target = _norm_extrinsic_hash(wrapper_hash) if wrapper_hash else None
        try:
            pending = list(sub.retrieve_pending_extrinsics() or [])
        except Exception:
            return None
        try:
            for ext_data in pending:
                if isinstance(ext_data, str):
                    ext_hex = ext_data
                elif isinstance(ext_data, (bytes, bytearray)):
                    ext_hex = ext_data.hex() if not str(ext_data).startswith("0x") else ext_data
                else:
                    ext_hex = str(ext_data)
                if isinstance(ext_hex, str) and not ext_hex.startswith("0x"):
                    ext_hex = f"0x{ext_hex}"
                decoded = decode_extrinsic(sub, ext_hex)
                if str(decoded.get("signer") or "") != str(signer_addr):
                    continue
                if target:
                    ext_h = self._decoded_extrinsic_hash(decoded, ext_hex)
                    blake_h = self._hash_extrinsic_hex(ext_hex)
                    if target in {ext_h, blake_h}:
                        return True
                if outer_nonce is not None and to_int(decoded.get("nonce")) == int(outer_nonce):
                    call_fn = str(decoded.get("call_function") or "").lower()
                    call_mod = str(decoded.get("call_module") or "").lower()
                    if call_mod == "mevshield" and call_fn == "submit_encrypted":
                        return True
        except Exception:
            return None
        return False

    def _resolve_mev_wrapper(
        self,
        ext_hash,
        submit_block,
        signer_addr,
        outer_nonce,
        timeout_blocks,
        *,
        sub=None,
        cancel_generation=None,
    ):
        """
        mevshieldbuy-style inclusion wait: scan blocks for the wrapper hash.

        Returns (status, success, incl_block, fail_detail):
          included | pending | dropped
        No era-length pool loops — those caused resign/1012/pending churn.
        """
        use_watch = sub is not None and sub is not self._sub
        target = _norm_extrinsic_hash(ext_hash)
        start = int(submit_block)
        outer = int(outer_nonce)
        era_cap = max(1, int(MEV_SHIELD_ERA_PERIOD) - 1)
        limit = max(1, min(int(timeout_blocks), era_cap))

        def _scan(block_num):
            if use_watch:
                with self._mev_watch_lock:
                    found, success, incl_block, _, fail_detail = (
                        self._find_extrinsic_in_block(
                            block_num,
                            target,
                            signer_addr=signer_addr,
                            outer_nonce=outer,
                            sub=self._mev_watch_sub,
                        )
                    )
            else:
                found, success, incl_block, _, fail_detail = (
                    self._find_extrinsic_in_block(
                        block_num,
                        target,
                        signer_addr=signer_addr,
                        outer_nonce=outer,
                        sub=self._sub,
                    )
                )
            if found:
                return "included", bool(success), incl_block, fail_detail
            return None

        def _nonce():
            return int(
                self._fetch_chain_nonce(
                    signer_addr, sub=True if use_watch else None
                )
            )

        def _pending():
            if use_watch:
                with self._mev_watch_lock:
                    return self._pending_has_wrapper(
                        signer_addr,
                        wrapper_hash=target,
                        outer_nonce=outer,
                        sub=self._mev_watch_sub,
                    )
            return self._pending_has_wrapper(
                signer_addr, wrapper_hash=target, outer_nonce=outer, sub=self._sub
            )

        # mevshieldbuy: poll submit_block+1 .. +timeout. Hash required.
        for current in range(start + 1, start + limit + 1):
            if cancel_generation is not None:
                self._raise_if_mev_cancelled(cancel_generation)
            self._wait_until_chain_block_rpc(current, use_watch=use_watch)
            hit = _scan(current)
            if hit:
                return hit

        # Nonce moved but hash encoding differed — hunt without inventing include.
        chain_nonce = _nonce()
        if self._mev_inflight_resolved_nonce(outer, chain_nonce) or (
            self._mev_wrapper_likely_in_flight(outer, chain_nonce)
        ):
            if use_watch:
                with self._mev_watch_lock:
                    head = int(self._fetch_head_block_number(self._mev_watch_sub))
            else:
                head = int(self._fetch_head_block_number(self._sub))
            for current in range(start + 1, max(start + 1, head) + 1):
                hit = _scan(current)
                if hit:
                    return hit
        # Never return "dropped" from the short resolve window — a single
        # author_pendingExtrinsics miss here caused resign while the wrapper
        # was still pooled → 1012 + stuck pending. Hand off to the longer wait.
        return "pending", False, None, None

    def _wait_mev_pending_resolve(
        self,
        ext_hash,
        submit_block,
        signer_addr,
        outer_nonce,
        *,
        cancel_generation=None,
        max_extra_blocks=6,
    ):
        """After initial miss: wait for inclusion or pool exit (bounded).

        Never re-sign while pending is True. Returns same tuple as resolve.
        """
        use_watch = True
        target = _norm_extrinsic_hash(ext_hash)
        outer = int(outer_nonce)
        start = int(submit_block)
        limit = max(1, int(max_extra_blocks))
        seen_absent = False

        def _scan(block_num):
            with self._mev_watch_lock:
                found, success, incl_block, _, fail_detail = self._find_extrinsic_in_block(
                    block_num,
                    target,
                    signer_addr=signer_addr,
                    outer_nonce=outer,
                    sub=self._mev_watch_sub,
                )
            if found:
                return "included", bool(success), incl_block, fail_detail
            return None

        def _nonce():
            return int(self._fetch_chain_nonce(signer_addr, sub=True))

        def _pending():
            with self._mev_watch_lock:
                return self._pending_has_wrapper(
                    signer_addr,
                    wrapper_hash=target,
                    outer_nonce=outer,
                    sub=self._mev_watch_sub,
                )

        with self._mev_watch_lock:
            head = int(self._get_mev_head_block(sub=self._mev_watch_sub))

        def _after_scan(current):
            nonlocal seen_absent
            chain_nonce = _nonce()
            if self._mev_inflight_resolved_nonce(outer, chain_nonce) or (
                self._mev_wrapper_likely_in_flight(outer, chain_nonce)
            ):
                hit = _scan(current)
                if hit:
                    return hit
                # Nonce moved but hash not in this block — keep scanning.
                # Never invent "included" without a hash match (wrong land
                # slot → inner not decrypted / silent mempool pending).
                return None
            pending = _pending()
            if pending is False:
                # Dual-socket confirm — one empty poll must not count as absent.
                confirmed = self._mev_pool_wrapper_state(
                    signer_addr, wrapper_hash=target, outer_nonce=outer
                )
                if confirmed is not False:
                    seen_absent = False
                    return None
                if seen_absent:
                    return "dropped", False, None, None
                seen_absent = True  # one-block 1012 cooldown
            elif pending is True:
                seen_absent = False
            return None

        # Catch up any blocks already produced since submit.
        for current in range(start + 1, int(head) + 1):
            if cancel_generation is not None:
                self._raise_if_mev_cancelled(cancel_generation)
            hit = _scan(current)
            if hit:
                return hit
            resolved = _after_scan(current)
            if resolved is not None:
                return resolved

        # Then wait forward a few more blocks.
        for step in range(limit):
            current = int(head) + 1 + step
            if cancel_generation is not None:
                self._raise_if_mev_cancelled(cancel_generation)
            self._wait_until_chain_block_rpc(current, use_watch=use_watch)
            hit = _scan(current)
            if hit:
                return hit
            resolved = _after_scan(current)
            if resolved is not None:
                return resolved
        # Final inclusion hunt — pending can be empty while the wrapper already
        # landed in a block we skipped during a transient scan miss.
        hunted = self._hunt_mev_wrapper_since(
            target, start, signer_addr, outer, use_watch=True
        )
        if hunted is not None:
            return hunted
        # Dual-socket confirm before drop — one empty pendingExtrinsics is not enough.
        pool = self._mev_pool_wrapper_state(
            signer_addr, wrapper_hash=target, outer_nonce=outer
        )
        if pool is False:
            return "dropped", False, None, None
        return "pending", False, None, None

    def _invalidate_mev_sign_caches(self):
        """Drop era/NextKey caches so a re-sign cannot reproduce the same extrinsic bytes."""
        self._mev_era_cache = None
        cache = getattr(self, "_mev_next_key_cache", None)
        if isinstance(cache, dict):
            cache.clear()

    def _prepare_mev_resign_after(
        self, after_block, *, cancel_generation=None, reason="re-sign"
    ):
        """
        Before re-signing: bust era/NextKey caches and wait until head is past
        the failed attempt. Same head + same key → identical ciphertext → 1012.
        Happy path never calls this.
        """
        del reason  # diagnostics only
        if cancel_generation is not None:
            self._raise_if_mev_cancelled(cancel_generation)
        self._invalidate_mev_sign_caches()
        target = int(after_block) + 1 if after_block is not None else None
        if target is None:
            head = int(
                self._with_watch_retry(
                    lambda s: self._fetch_head_block_number(s),
                    attempts=3,
                    label="mev_resign_head",
                )
            )
            target = head + 1
        estimated = self._estimated_mev_block_duration_sec()
        slice_sec = max(float(estimated) * 2.0, 20.0)
        while True:
            if cancel_generation is not None:
                self._raise_if_mev_cancelled(cancel_generation)
            self._wait_until_chain_block_rpc(
                target, max_wait_sec=slice_sec, use_watch=True
            )
            head = int(
                self._with_watch_retry(
                    lambda s: self._fetch_head_block_number(s),
                    attempts=3,
                    label="mev_resign_head",
                )
            )
            if head >= target:
                break
        self._invalidate_mev_sign_caches()
        return int(head)

    def _try_clear_stale_mev_inflight(self, signer_addr):
        with self._mev_meta_lock:
            inflight = dict(self._mev_inflight.get(signer_addr) or {})
        if not inflight:
            return False
        outer_nonce = int(inflight.get("outer_nonce"))
        chain_nonce = int(self._fetch_chain_nonce(signer_addr))
        if self._mev_inflight_resolved_nonce(outer_nonce, chain_nonce):
            self._clear_mev_inflight(signer_addr)
            self._commit_nonce_after_success(signer_addr, chain_nonce)
            return True
        started = float(inflight.get("started_at") or 0.0)
        age = (time.monotonic() - started) if started else 0.0
        block_dur = float(self._estimated_mev_block_duration_sec())
        wrapper_hash = inflight.get("wrapper_hash")
        if self._mev_wrapper_likely_in_flight(outer_nonce, chain_nonce):
            # N+1 used to lock forever. Age out after ~3 blocks if wrapper is gone.
            pending = self._pending_has_wrapper(
                signer_addr, wrapper_hash=wrapper_hash, outer_nonce=outer_nonce
            )
            n1_budget = max(block_dur * 3.0, 20.0)
            if pending is True and age < max(1, int(MEV_SHIELD_ERA_PERIOD)) * block_dur:
                return False
            if age < n1_budget and pending is not False:
                return False
            self._clear_mev_inflight(signer_addr)
            self._reconcile_nonce_after_mev_failure(signer_addr)
            return True
        if chain_nonce <= outer_nonce:
            pending = self._pending_has_wrapper(
                signer_addr, wrapper_hash=wrapper_hash, outer_nonce=outer_nonce
            )
            # True or None: keep lock through era window (None ≠ dropped).
            if pending is not False:
                era_budget = max(1, int(MEV_SHIELD_ERA_PERIOD)) * block_dur
                if age < era_budget:
                    return False
                self._clear_mev_inflight(signer_addr)
                self._reconcile_nonce_after_mev_failure(signer_addr)
                return True
            if age < block_dur * 2:
                return False
            self._clear_mev_inflight(signer_addr)
            self._reconcile_nonce_after_mev_failure(signer_addr)
            return True
        return False

    def _assert_no_mev_inflight(self, signer_addr):
        if self._try_clear_stale_mev_inflight(signer_addr):
            return
        with self._mev_meta_lock:
            inflight = dict(self._mev_inflight.get(signer_addr) or {})
        if not inflight:
            return
        outer_nonce = int(inflight.get("outer_nonce"))
        chain_nonce = int(self._fetch_chain_nonce(signer_addr))
        if self._mev_inflight_resolved_nonce(outer_nonce, chain_nonce):
            self._clear_mev_inflight(signer_addr)
            self._commit_nonce_after_success(signer_addr, chain_nonce)
            return
        wrapper_hash = str(inflight.get("wrapper_hash") or "")
        short_hash = f"{wrapper_hash[:18]}…" if wrapper_hash else "?"
        raise RuntimeError(
            f"MEV wrapper still pending ({short_hash}, outer nonce {outer_nonce}, "
            f"chain nonce {chain_nonce}). "
            "Wait for inclusion/inner confirm, or POST /api/nonce/refresh after it clears. "
            "Plain (non-MEV) submits are also blocked until then to protect the nonce."
        )

    def _take_nonce(self, signer_addr):
        # Block plain submits while a MEV round owns outer/inner nonces for this signer.
        self._assert_no_mev_inflight(signer_addr)
        # Hot-path fast nonce: rely on the background nonce watcher (refreshes the
        # chain nonce cache every block) plus the local hint, so we avoid a
        # synchronous get_account_nonce RPC round trip on every submit.
        # Only fetch from chain when the cache is cold (or was cleared after a
        # stale-nonce error), which keeps correctness while removing latency.
        hinted = self._nonce_hint.get(signer_addr)
        cached = self._nonce_chain_cache.get(signer_addr)
        if hinted is None and cached is None:
            chain_nonce = self._with_rpc_retry(
                lambda: self._sub.get_account_nonce(signer_addr),
                attempts=3,
                label="get_account_nonce",
            )
            nonce = int(chain_nonce)
        else:
            nonce = 0
            if cached is not None:
                nonce = max(nonce, int(cached))
            if hinted is not None:
                nonce = max(nonce, int(hinted))
        self._nonce_hint[signer_addr] = nonce + 1
        self._nonce_chain_cache[signer_addr] = nonce + 1
        return nonce

    def _clear_nonce_hint(self, signer_addr):
        self._nonce_hint.pop(signer_addr, None)
        self._nonce_chain_cache.pop(signer_addr, None)

    def refresh_nonce_cache_manual(self):
        addresses = self._active_signer_addresses()
        # Hold the lock across the whole refresh so the get_account_nonce RPC on
        # self._sub cannot collide with an in-flight submit (RLock allows the
        # nested re-acquire inside _refresh_nonce_cache_once).
        with self._mev_meta_lock:
            for addr in addresses:
                self._mev_inflight.pop(addr, None)
        with self._lock:
            for addr in addresses:
                self._nonce_hint.pop(addr, None)
                self._nonce_chain_cache.pop(addr, None)
            self._refresh_nonce_cache_once(force=True)
            signer_nonce = self._nonce_chain_cache.get(self.signer_ss58)
            proxy_nonce = (
                self._nonce_chain_cache.get(self.proxy_ss58) if self.proxy_ss58 else None
            )
        return {
            "refreshed_at": utc_now_iso(),
            "block_number": self._latest_block_number,
            "signer": self.signer_ss58,
            "signer_nonce": signer_nonce,
            "proxy": self.proxy_ss58 or "",
            "proxy_nonce": proxy_nonce,
        }

