    async def prepend_local_mempool_row(self, row: dict, *, ttl_sec=45.0):
        """Push a user submit into the mempool panel immediately (optimistic or
        just-broadcast), merged ahead of the next author_pendingExtrinsics poll."""
        async with self._lock:
            row = dict(row or {})
            tx_hash = str(row.get("hash") or "").strip()
            netuid = str(row.get("netuid") or "").strip()
            norm_h = self._normalize_mempool_hash(tx_hash)
            call_l = str(row.get("call") or "").lower()
            addr = self._mempool_row_address(row)
            # Drop stale pending / duplicate MevShield pins for this submit.
            kept = []
            for p in self._local_mempool_pins:
                prow = p.get("row") or {}
                ph = str(prow.get("hash") or "").strip()
                pnorm = self._normalize_mempool_hash(ph)
                pcall = str(prow.get("call") or "").lower()
                if ph.startswith("pending-") and (
                    str(prow.get("netuid") or "").strip() == netuid
                    or "mevshield" in call_l
                ):
                    continue
                if norm_h and pnorm == norm_h:
                    continue
                if (
                    "mevshield" in call_l
                    and "mevshield" in pcall
                    and self._mempool_row_address(prow) == addr
                ):
                    continue
                kept.append(p)
            self._local_mempool_pins = kept
            self._local_mempool_pins.insert(
                0, {"row": row, "expires_at": time.time() + float(ttl_sec)}
            )
            merged_rows = self._merge_mempool_rows(self._mempool_chain_rows)
            self._mempool_seq += 1
            payload = dict(self._mempool_payload)
            payload["rows"] = merged_rows
            payload["pending_count"] = max(int(payload.get("pending_count") or 0), len(merged_rows))
            payload["new_count"] = max(int(payload.get("new_count") or 0), 1)
            payload["ts"] = utc_now_iso()
            self._mempool_payload = payload
            msg = {
                "type": "mempool_snapshot",
                "version": 1,
                "sequence": self._mempool_seq,
                "notifications_sequence": self._mempool_seq,
                "sent_at": utc_now_iso(),
                "payload": dict(payload),
            }
        await self._broadcast(msg)

    async def drop_local_mempool_row(self, tx_hash: str):
        """Remove a local pin once the wrapper is included/failed (stop false pending)."""
        norm_h = self._normalize_mempool_hash(tx_hash)
        if not norm_h:
            return
        async with self._lock:
            before = len(self._local_mempool_pins)
            self._local_mempool_pins = [
                p
                for p in self._local_mempool_pins
                if self._normalize_mempool_hash((p.get("row") or {}).get("hash"))
                != norm_h
            ]
            if len(self._local_mempool_pins) == before:
                return
            merged_rows = self._merge_mempool_rows(self._mempool_chain_rows)
            self._mempool_seq += 1
            payload = dict(self._mempool_payload)
            payload["rows"] = merged_rows
            payload["ts"] = utc_now_iso()
            self._mempool_payload = payload
            msg = {
                "type": "mempool_snapshot",
                "version": 1,
                "sequence": self._mempool_seq,
                "notifications_sequence": self._mempool_seq,
                "sent_at": utc_now_iso(),
                "payload": dict(payload),
            }
        await self._broadcast(msg)


