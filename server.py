def _hashes_for_pending_hexes(decode_cache: dict, hex_list: list) -> set[str]:
    out: set[str] = set()
    for ext_hex in hex_list:
        ext = decode_cache.get(ext_hex) or {}
        h = SnapshotState._normalize_mempool_hash(ext.get("hash"))
        if h:
            out.add(h)
    return out


def _row_from_new_extrinsic(row: dict, new_hashes: set[str]) -> bool:
    if not new_hashes:
        return False
    return SnapshotState._normalize_mempool_hash((row or {}).get("hash")) in new_hashes


async def mempool_collector(
    config: RuntimeConfig,
    state: SnapshotState,
    alpha_price_cache: AlphaPriceCache,
    address_book_seq_getter=None,
    auto_unstake_handler=None,
    follow_stake_handler=None,
    identity_stake_handler=None,
):
    decode_cache: dict[str, dict] = {}
    first_seen_by_extrinsic: dict[str, float] = {}
    last_pending_set: set[str] = set()
    poll_index = 0
    rpc_timeout_sec = float(os.getenv("MEMPOOL_RPC_TIMEOUT_SEC") or "15")
    decode_timeout_sec = float(os.getenv("MEMPOOL_DECODE_TIMEOUT_SEC") or "5")

    while True:
        substrate = None
        try:
            substrate = await asyncio.to_thread(_new_substrate, config.endpoint)
            # Keep decode_cache across reconnects — raw hex → decoded payload is stable
            # and clearing forces a full re-decode burst that stalls detection.

            while True:
                started = time.perf_counter()
                try:
                    response = await asyncio.wait_for(
                        asyncio.to_thread(
                            substrate.rpc_request, "author_pendingExtrinsics", []
                        ),
                        timeout=rpc_timeout_sec,
                    )
                    pending = response.get("result", [])
                    now_ts = time.time()
                    current_pending_set = set(pending)
                    new_pending = [ext for ext in pending if ext not in last_pending_set]
                    pending_changed = current_pending_set != last_pending_set

                    for ext_hex in pending:
                        first_seen_by_extrinsic.setdefault(ext_hex, now_ts)
                    first_seen_by_extrinsic = {
                        k: v
                        for k, v in first_seen_by_extrinsic.items()
                        if k in current_pending_set
                    }

                    for ext_hex in list(decode_cache):
                        if ext_hex not in current_pending_set:
                            del decode_cache[ext_hex]

                    missing = [ext_hex for ext_hex in pending if ext_hex not in decode_cache]
                    if missing:
                        batch_timeout = min(
                            60.0,
                            decode_timeout_sec * max(1, len(missing)),
                        )
                        batch = await asyncio.wait_for(
                            asyncio.to_thread(
                                decode_extrinsics_batch, substrate, missing
                            ),
                            timeout=batch_timeout,
                        )
                        decode_cache.update(batch)

                    decoded_items = []
                    for ext_hex in pending:
                        ext = decode_cache.get(ext_hex)
                        if ext is None:
                            continue
                        raw_hex = ext.get("raw_hex") or ext_hex
                        ext["_age_seconds"] = (
                            (now_ts - first_seen_by_extrinsic[raw_hex])
                            if raw_hex in first_seen_by_extrinsic
                            else None
                        )
                        decoded_items.append(ext)

                    alpha_prices, price_block = alpha_price_cache.snapshot()
                    rows, transfer_rows, other_notification_rows = await asyncio.to_thread(
                        build_mempool_stake_display,
                        decoded_items,
                        alpha_prices,
                        substrate,
                        price_block,
                        stake_only=True,
                        include_mev_shield=True,
                    )

                    # Bot handlers only need to react to newly seen extrinsics in
                    # the mempool — re-running on every poll was the main CPU sink.
                    new_hashes = (
                        _hashes_for_pending_hexes(decode_cache, new_pending)
                        if new_pending
                        else set()
                    )
                    if callable(auto_unstake_handler) and new_hashes:
                        for row in rows:
                            if not _row_from_new_extrinsic(row, new_hashes):
                                continue
                            with contextlib.suppress(Exception):
                                auto_unstake_handler("mempool", row, price_block)
                    if callable(follow_stake_handler) and new_hashes:
                        for row in rows:
                            if not _row_from_new_extrinsic(row, new_hashes):
                                continue
                            with contextlib.suppress(Exception):
                                follow_stake_handler("mempool", row, price_block)
                    if callable(identity_stake_handler) and new_hashes:
                        for row in other_notification_rows:
                            if not _row_from_new_extrinsic(row, new_hashes):
                                continue
                            with contextlib.suppress(Exception):
                                identity_stake_handler("mempool", row, price_block)
                    latency_ms = (time.perf_counter() - started) * 1000.0
                    await state.publish_mempool(
                        {
                            "ts": utc_now_iso(),
                            "poll": poll_index,
                            "pending_count": len(pending),
                            "new_count": len(new_pending),
                            "latency_ms": round(latency_ms, 3),
                            "price_block": price_block,
                            "rows": rows,
                            "transfer_rows": transfer_rows,
                            "other_notification_rows": other_notification_rows,
                            "address_book_seq": (
                                int(address_book_seq_getter())
                                if callable(address_book_seq_getter)
                                else 0
                            ),
                            "error": None,
                        },
                        force_broadcast=bool(new_pending or pending_changed),
                    )
                    last_pending_set = current_pending_set
                    poll_index += 1
                except asyncio.TimeoutError:
                    raise RuntimeError("mempool poll timed out") from None
                except Exception as exc:
                    await _publish_mempool_error(
                        state,
                        poll_index,
                        str(exc),
                        address_book_seq_getter=address_book_seq_getter,
                    )
                    await asyncio.sleep(1.0)

                elapsed = time.perf_counter() - started
                sleep_s = max(0.0, config.mempool_poll_interval - elapsed)
                await asyncio.sleep(sleep_s)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            await _publish_mempool_error(
                state,
                poll_index,
                str(exc),
                address_book_seq_getter=address_book_seq_getter,
            )
            await asyncio.sleep(2.0)
        finally:
            with contextlib.suppress(Exception):
                if substrate is not None:
                    substrate.close()


async def block_collector(
    config: RuntimeConfig,
    state: SnapshotState,
    alpha_price_cache: AlphaPriceCache,
    address_book_seq_getter=None,
    auto_unstake_handler=None,
    follow_stake_handler=None,
):
    last_block = None

    while True:
        sub_headers = None
        sub_parser = None
        sub_task = None
        try:
            sub_headers = _new_substrate(config.endpoint)
            sub_parser = _new_substrate(config.endpoint)

            # Head-only policy: no historical catch-up.
            # On (re)connect, publish the current head once immediately.
            head_hash = await asyncio.to_thread(sub_headers.get_chain_head)
            head = int(await asyncio.to_thread(sub_headers.get_block_number, head_hash))
            if last_block is None or head != last_block:
                head_received_at_ms = int(time.time() * 1000)
                alpha_prices, _ = alpha_price_cache.snapshot()
                report = await asyncio.to_thread(parse_block, sub_parser, head, alpha_prices)
                rows = list(report.get("stake_rows", []))
                if callable(auto_unstake_handler):
                    for row in rows:
                        with contextlib.suppress(Exception):
                            auto_unstake_handler("block", row, int(head))
                if callable(follow_stake_handler):
                    for row in rows:
                        with contextlib.suppress(Exception):
                            follow_stake_handler("block", row, int(head))
                await state.publish_block(
                    {
                        "ts": report.get("block_ts") or utc_now_iso(),
                        "block_ts_ms": report.get("block_ts_ms"),
                        "received_at_ms": head_received_at_ms,
                        "block_number": report.get("block_number", head),
                        "block_hash": report.get("block_hash", ""),
                        "extrinsics_count": report.get("extrinsics_count", 0),
                        "events_total": report.get("events_total", 0),
                        "rows": rows,
                        "transfer_rows": report.get("transfer_rows", []),
                        "other_notification_rows": report.get("other_notification_rows", []),
                        "address_book_seq": (
                            int(address_book_seq_getter()) if callable(address_book_seq_getter) else 0
                        ),
                        "ethereum_stake_transfer_chains": report.get(
                            "ethereum_stake_transfer_chains", []
                        ),
                        "error": None,
                    }
                )
                last_block = head

            loop = asyncio.get_running_loop()
            block_queue: asyncio.Queue[tuple[int, int]] = asyncio.Queue(maxsize=1)
            stop_flag = threading.Event()

            def _push_latest_block(bn: int):
                # Head-only queue: keep only the newest block number.
                received_at_ms = int(time.time() * 1000)
                if block_queue.full():
                    with contextlib.suppress(asyncio.QueueEmpty):
                        block_queue.get_nowait()
                block_queue.put_nowait((int(bn), received_at_ms))

            def _on_block(obj, _update_nr, _subscription_id):
                if stop_flag.is_set():
                    return {"stop": True}
                header = obj.get("header") if isinstance(obj, dict) else None
                if not isinstance(header, dict):
                    return None
                bn = parse_block_number(header.get("number"))
                if bn is None or bn == last_block:
                    return None
                loop.call_soon_threadsafe(_push_latest_block, int(bn))
                return None

            sub_task = asyncio.create_task(
                asyncio.to_thread(sub_headers.subscribe_block_headers, _on_block)
            )

            try:
                while True:
                    if sub_task.done():
                        await sub_task
                        break
                    try:
                        bn, received_at_ms = await asyncio.wait_for(
                            block_queue.get(),
                            timeout=max(1.0, config.block_poll_interval),
                        )
                    except asyncio.TimeoutError:
                        continue
                    if bn == last_block:
                        continue

                    alpha_prices, _ = alpha_price_cache.snapshot()
                    report = await asyncio.to_thread(parse_block, sub_parser, int(bn), alpha_prices)
                    rows = list(report.get("stake_rows", []))
                    if callable(auto_unstake_handler):
                        for row in rows:
                            with contextlib.suppress(Exception):
                                auto_unstake_handler("block", row, int(bn))
                    if callable(follow_stake_handler):
                        for row in rows:
                            with contextlib.suppress(Exception):
                                follow_stake_handler("block", row, int(bn))
                    await state.publish_block(
                        {
                            "ts": report.get("block_ts") or utc_now_iso(),
                            "block_ts_ms": report.get("block_ts_ms"),
                            "received_at_ms": int(received_at_ms),
                            "block_number": report.get("block_number", int(bn)),
                            "block_hash": report.get("block_hash", ""),
                            "extrinsics_count": report.get("extrinsics_count", 0),
                            "events_total": report.get("events_total", 0),
                            "rows": rows,
                            "transfer_rows": report.get("transfer_rows", []),
                        "other_notification_rows": report.get("other_notification_rows", []),
                            "address_book_seq": (
                                int(address_book_seq_getter()) if callable(address_book_seq_getter) else 0
                            ),
                            "ethereum_stake_transfer_chains": report.get(
                                "ethereum_stake_transfer_chains", []
                            ),
                            "error": None,
                        }
                    )
                    last_block = int(bn)
            finally:
                stop_flag.set()
                if sub_task is not None and not sub_task.done():
                    sub_task.cancel()
                    with contextlib.suppress(Exception):
                        await sub_task
                if sub_headers is not None:
                    with contextlib.suppress(Exception):
                        sub_headers.close()
                if sub_parser is not None:
                    with contextlib.suppress(Exception):
                        sub_parser.close()
        except Exception as exc:
            await state.publish_block(
                {
                    "ts": utc_now_iso(),
                    "received_at_ms": int(time.time() * 1000),
                    "block_number": 0,
                    "block_hash": "",
                    "extrinsics_count": 0,
                    "events_total": 0,
                    "rows": [],
                    "transfer_rows": [],
                    "address_book_seq": (
                        int(address_book_seq_getter()) if callable(address_book_seq_getter) else 0
                    ),
                    "ethereum_stake_transfer_chains": [],
                    "error": str(exc),
                }
            )
            await asyncio.sleep(1.0)



