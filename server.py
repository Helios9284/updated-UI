    def _compose_force_batch(self, inner_calls, use_proxy, block_hash=None):
        # inner_calls are already-composed SubtensorModule calls (each composed
        # via _compose_call(..., use_proxy=False), so no proxy/lock nesting here).
        # We wrap them once in Utility.force_batch, then (optionally) once in
        # Proxy.proxy so the whole batch executes as the real account.
        compose_kw = {"block_hash": block_hash} if block_hash else {}
        with self._read_lock:
            batch = self._with_read_retry(
                lambda s: s.compose_call(
                    call_module="Utility",
                    call_function="force_batch",
                    call_params={"calls": list(inner_calls)},
                    **compose_kw,
                ),
                attempts=3,
                label="compose_force_batch",
            )
            if not use_proxy:
                return batch
            return self._with_read_retry(
                lambda s: s.compose_call(
                    call_module="Proxy",
                    call_function="proxy",
                    call_params={
                        "real": self.real_ss58,
                        "force_proxy_type": self.force_proxy_type,
                        "call": batch,
                    },
                    **compose_kw,
                ),
                attempts=3,
                label="compose_force_batch_proxy",
            )

    def submit_batch(self, ops, use_proxy, mev_protection=False):
        if not isinstance(ops, list) or not ops:
            raise RuntimeError("ops must be a non-empty list")
        if len(ops) > 50:
            raise RuntimeError("too many ops in batch (max 50)")
        signer_kp, signer_addr = self._signer_for(use_proxy)
        # One portfolio snapshot reused for all remove-hotkey resolutions.
        snapshot = self.wallet_portfolio_snapshot()
        inner_calls = []
        items = []
        for raw_op in ops:
            op = raw_op or {}
            action = str(op.get("action") or "").strip().lower()
            netuid = to_int(op.get("netuid"))
            if netuid is None:
                raise RuntimeError("each op requires a netuid")
            netuid = int(netuid)

            if action == "add":
                amount_tao = op.get("amount_tao")
                if amount_tao is None:
                    amount_tao = op.get("amount")
                amount_rao = tao_to_rao(amount_tao)
                if amount_rao is None or amount_rao <= 0:
                    raise RuntimeError(f"add op (netuid {netuid}) requires amount_tao > 0")
                slippage_pct = self._effective_slippage_pct(
                    op.get("slippage_pct") or 0, mev_protection
                )
                hotkey_addr = str(op.get("hotkey") or "").strip() or self._validator_hotkey_for_add(
                    netuid
                )
                limit_price, px, price_block = self._limit_price_rao(
                    netuid, slippage_pct, side="add"
                )
                params = {
                    "hotkey": hotkey_addr,
                    "netuid": netuid,
                    "amount_staked": int(amount_rao),
                    "limit_price": int(limit_price),
                    "allow_partial": False,
                }
                inner = self._compose_call("add_stake_limit", params, use_proxy=False)
                items.append(
                    {
                        "action": "add_stake_limit",
                        "netuid": netuid,
                        "hotkey": hotkey_addr,
                        "amount_tao": float(amount_tao),
                        "amount_rao": int(amount_rao),
                        "slippage_pct": slippage_pct,
                        "alpha_price_tao": float(px),
                        "alpha_price_block": price_block,
                        "limit_price_rao": int(limit_price),
                    }
                )
            elif action in ("remove_full", "remove", "remove_stake_full"):
                hotkey_addr = self._resolve_remove_hotkey(
                    netuid, hotkey_override=op.get("hotkey"), snapshot=snapshot
                )
                inner = self._compose_remove_full_call(netuid, hotkey_addr, use_proxy=False)
                items.append(
                    {
                        "action": "remove_stake_full_limit",
                        "netuid": netuid,
                        "hotkey": hotkey_addr,
                    }
                )
            elif action in ("remove_amount", "remove_stake_amount"):
                amount_alpha = op.get("amount_alpha")
                if amount_alpha is None:
                    amount_alpha = op.get("amount")
                amount_unstaked = tao_to_rao(amount_alpha)
                if amount_unstaked is None or amount_unstaked <= 0:
                    raise RuntimeError(
                        f"remove_amount op (netuid {netuid}) requires amount_alpha > 0"
                    )
                slippage_pct = self._effective_slippage_pct(
                    op.get("slippage_pct") or 0, mev_protection
                )
                hotkey_addr = self._resolve_remove_hotkey(
                    netuid, hotkey_override=op.get("hotkey"), snapshot=snapshot
                )
                limit_price, px, price_block = self._limit_price_rao(
                    netuid, slippage_pct, side="remove"
                )
                params = {
                    "hotkey": hotkey_addr,
                    "netuid": netuid,
                    "amount_unstaked": int(amount_unstaked),
                    "limit_price": int(limit_price),
                    "allow_partial": False,
                }
                inner = self._compose_call("remove_stake_limit", params, use_proxy=False)
                items.append(
                    {
                        "action": "remove_stake_limit",
                        "netuid": netuid,
                        "hotkey": hotkey_addr,
                        "amount_alpha": float(amount_alpha),
                        "amount_alpha_rao": int(amount_unstaked),
                        "slippage_pct": slippage_pct,
                        "alpha_price_tao": float(px),
                        "alpha_price_block": price_block,
                        "limit_price_rao": int(limit_price),
                    }
                )
            else:
                raise RuntimeError(f"unknown op action: {action!r}")

            inner_calls.append(inner)

        batch_call = self._compose_force_batch(inner_calls, use_proxy)
        first = items[0] if items else {}
        first_amount = first.get("amount_tao")
        if first_amount is None and first.get("amount_alpha") is not None:
            px0 = first.get("alpha_price_tao")
            if px0 is not None:
                with contextlib.suppress(Exception):
                    first_amount = float(first["amount_alpha"]) * float(px0)
        first_row = "remove" if "remove" in str(first.get("action") or "") else "add"
        if mev_protection:
            tx = self._submit_with_mev_retry(
                signer_kp,
                signer_addr,
                batch_call,
                use_proxy=bool(use_proxy),
                mempool_hint={
                    "netuid": first.get("netuid"),
                    "amount_tao": first_amount,
                    "slippage_pct": first.get("slippage_pct"),
                    "row_type": first_row,
                },
            )
        else:
            tx = self._submit_with_retry(signer_kp, signer_addr, batch_call)
        tx_hash = str(tx["hash"])
        for it in items:
            with contextlib.suppress(Exception):
                self._reward_tracker.mark_user_action(it["netuid"], it["hotkey"])
            # MEV already pushed MevShield.submit_encrypted at wrapper-accept time.
            if mev_protection:
                continue
            action = str(it.get("action") or "")
            row_type = "remove" if "remove" in action else "add"
            amount_tao = it.get("amount_tao")
            if amount_tao is None and it.get("amount_alpha") is not None:
                px = it.get("alpha_price_tao")
                if px is not None:
                    with contextlib.suppress(Exception):
                        amount_tao = float(it["amount_alpha"]) * float(px)
            slippage_pct = float(it.get("slippage_pct") or 0)
            with contextlib.suppress(Exception):
                self._notify_mempool_listener(
                    self._build_local_mempool_row(
                        action=action,
                        tx_hash=tx_hash,
                        signer_addr=signer_addr,
                        netuid=int(it["netuid"]),
                        amount_tao=float(amount_tao or 0),
                        slippage_pct=slippage_pct,
                        use_proxy=use_proxy,
                        row_type=row_type,
                    )
                )
        return {
            "ok": True,
            "action": "force_batch",
            "submitted_at": utc_now_iso(),
            "signer": signer_addr,
            "real": self.real_ss58 if use_proxy else signer_addr,
            "proxy_used": bool(use_proxy),
            "op_count": len(items),
            "items": items,
            "tx_hash": tx_hash,
            "nonce": tx["nonce"],
            "materials_ms": tx.get("materials_ms"),
            "pool_submit_latency_ms": tx.get("pool_submit_latency_ms"),
            "submit_latency_ms": tx.get("submit_latency_ms"),
            "submit_attempt": tx.get("attempt"),
            "submit_mode": tx.get("mode", "proxy" if use_proxy else "default"),
            "inner_nonce": tx.get("inner_nonce"),
            "inner_hash": tx.get("inner_hash"),
            "inclusion_block": tx.get("inclusion_block"),
            "mev_confirmed": tx.get("mev_confirmed"),
            "mev_protection": bool(mev_protection),
        }


