class PositionRewardTracker:
    """In-memory realized-reward tracker (Option B).

    Accumulates emission-driven alpha growth per (netuid, hotkey) position by
    diffing the per-block alpha snapshots the portfolio worker already collects.
    Stake/unstake actions are excluded: explicitly via mark_user_action() for
    app-initiated submits, and heuristically for any single-step alpha jump that
    is negative (unstake/move out) or larger than USER_ACTION_FRACTION of the
    position (a stake-in). Real per-tempo dividends are a tiny fraction of stake,
    so they fall well below the threshold. Pure in-memory math — no extra RPC.
    """

    SECONDS_PER_YEAR = 365 * 24 * 3600
    WINDOW_SEC = 24 * 3600
    CHECKPOINT_SEC = 60.0
    USER_ACTION_FRACTION = 0.02

    def __init__(self):
        self._lock = threading.Lock()
        self._state = {}

    def mark_user_action(self, netuid, hotkey):
        key = (int(netuid), str(hotkey))
        with self._lock:
            st = self._state.get(key)
            if st is not None:
                st["pending_user_action"] = True

    def update(self, positions, ts=None):
        ts = float(ts if ts is not None else time.time())
        out = {}
        with self._lock:
            seen = set()
            for netuid, hotkey, alpha in positions:
                key = (int(netuid), str(hotkey))
                seen.add(key)
                alpha = float(alpha)
                st = self._state.get(key)
                if st is None:
                    st = {
                        "prev_alpha": alpha,
                        "reward_accum": 0.0,
                        "start_ts": ts,
                        "last_checkpoint_ts": ts,
                        "checkpoints": deque([(ts, 0.0)]),
                        "pending_user_action": False,
                    }
                    self._state[key] = st
                else:
                    d = alpha - st["prev_alpha"]
                    is_user = bool(st.get("pending_user_action"))
                    if not is_user:
                        if d < 0:
                            is_user = True
                        elif (
                            d > 0
                            and st["prev_alpha"] > 0
                            and d > st["prev_alpha"] * self.USER_ACTION_FRACTION
                        ):
                            is_user = True
                    if (not is_user) and d > 0:
                        st["reward_accum"] += d
                    st["prev_alpha"] = alpha
                    st["pending_user_action"] = False
                    if ts - st["last_checkpoint_ts"] >= self.CHECKPOINT_SEC:
                        st["checkpoints"].append((ts, st["reward_accum"]))
                        st["last_checkpoint_ts"] = ts
                    cutoff = ts - self.WINDOW_SEC
                    cps = st["checkpoints"]
                    while len(cps) > 1 and cps[1][0] < cutoff:
                        cps.popleft()

                cps = st["checkpoints"]
                base_ts, base_accum = cps[0]
                reward_window = max(0.0, st["reward_accum"] - base_accum)
                elapsed = max(1.0, ts - base_ts)
                apy = (reward_window / alpha) * (self.SECONDS_PER_YEAR / elapsed) * 100.0 if alpha > 0 else 0.0
                out[key] = {
                    "reward_alpha_total": st["reward_accum"],
                    "reward_alpha_window": reward_window,
                    "reward_window_sec": elapsed,
                    "apy_pct": apy,
                }
            # Drop state for positions that have fully disappeared so memory does
            # not grow unbounded across many netuids over a long uptime.
            for key in list(self._state.keys()):
                if key not in seen:
                    del self._state[key]
        return out


class StakeSubmitService:
    def __init__(self, config: StakeRuntimeConfig):
        self.config = config
        # Read-only fast path endpoint (portfolio/block/price). Falls back to the
        # submit endpoint when unset so behavior is unchanged if no local node.
